def norm_license(raw):
    t = re.sub(r"\s+", "", raw or "")
    t = re.sub(r"^\(?기타:?", "", t).strip(",.;:·-")
    while t.endswith(")") and t.count(")") > t.count("("):
        t = t[:-1]
    while t.startswith("(") and t.count("(") > t.count(")"):
        t = t[1:]
    if t.startswith("(") and t.endswith(")"):
        t = t[1:-1]
    if not t or len(t) < 2:
        return None
    m = re.match(r"^(특급|\d급)(.+)$", t)
    if m:
        t = m.group(2) + m.group(1)
    t = ALIASES.get(t, t)
    if re.fullmatch(r"(특급|\d급|\d종)", t) or re.search(r"경력|또는|이상|우대|필수|가능|소지|보유|나이|성별|여성|남성|선생님|분$", t):
        return None
    if not re.search(r"(사|기사|기능사|기술사|기능장|면허|자격|이수|급|\)|증|관리사|지도사|교사|통역사|의사|사보|영어|ITQ|GTQ|처리|프로세서|능력|관리|기능|조종사)$", t) and t not in ALIASES.values():
        return None
    if t.count("(") != t.count(")"):
        t = t.replace("(", "").replace(")", "")
    for pat, name in NON_LICENSE.items():
        if re.search(pat, t):
            return name
    return t


def parent_name(name):
    for pat in [r"^(요양보호사|사회복지사|보육교사|소방안전관리자|컴퓨터활용능력|청소년지도사|생활스포츠지도사|평생교육사|직업상담사|유치원정교사|중등학교정교사|정교사)(\d급|특급)$",
                r"^(자동차운전면허)(1종보통|1종대형|2종보통|1종소형|2종소형|1종특수.*)$",
                r"^(전산세무|전산회계|세무회계)(\d급)$"]:
        m = re.match(pat, name)
        if m:
            return m.group(1)
    if name.startswith("건설기계조종사면허("):
        return "건설기계조종사면허"
    return None


