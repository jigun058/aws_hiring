def license_category(name):
    name = re.sub(r"\(.*?\)$", "", name) if not name.startswith("건설기계") else name
    if name == "건강진단결과서(보건증)" or "자격 아님" in name:
        return "기타 요건(자격 아님)"
    if re.search(r"(기술사|기능장|산업기사|기능사)$", name) or (name.endswith("기사") and "운전기사" not in name):
        return "국가기술자격"
    if re.search(r"^(컴퓨터활용능력|워드프로세서|직업상담사|사무자동화)", name):
        return "국가기술자격"
    if re.search(r"운전면허|조종사면허|운전자격|운송종사자격", name):
        return "운전·운송 면허/자격"
    if re.search(NATIONAL_PRO, name):
        return "국가전문자격·면허"
    if re.search(r"이수|교육|수료", name):
        return "교육 이수"
    if re.search(r"전산세무|전산회계|세무회계|재경관리사|회계관리|ITQ|GTQ|FLEX|무역영어|정보기술자격|문서실무사|CNC기계절삭가공사", name):
        return "국가공인·민간자격"
    return "기타·미분류"


