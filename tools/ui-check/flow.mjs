// 다섯 단계 한 바퀴 + 공고 분석·재취업 이야기 화면 캡처. 폭: node flow.mjs 1024
import { open } from './lib.mjs'
const W = +(process.argv[2] || 1280)
const { p, shot, idle, close } = await open('flow', { width: W })
const sc = y => p.locator('main .overflow-y-auto').first().evaluate((e, y) => e.scrollTop = y, y)
await shot('00-landing')
await p.getByText('시작하기 →').click(); await shot('01-step1')
const chat = p.locator('#chat-input')
await chat.fill('마트에서 8년 동안 재고 관리 사무를 했어요. 매일 발주서를 확인하고 입고 수량을 전산에 입력했어요. 그 뒤로 반찬가게에서 2년 동안 포장과 계산 아르바이트를 했어요.')
await chat.press('Enter'); await idle(); await shot('02-step1-chat')
await chat.fill('월말 재고 차이를 3%에서 1%로 줄였어요'); await chat.press('Enter'); await idle(); await shot('03-step1-answer')
await p.getByRole('button', { name: '경험 카드 만들기 →' }).click(); await shot('04-step2')
await p.getByRole('button', { name: '직무 추천 받기 →' }).click(); await idle(); await shot('05-step3')
await sc(560); await shot('06-step3-detail')
await p.getByRole('button', { name: '이 직무 공고 보기 →' }).click(); await idle(); await shot('07-step4')
await p.locator('select').first().selectOption('서울'); await p.waitForTimeout(1500); await shot('08-step4-seoul')
await p.getByRole('button', { name: '부족한 역량 채우기 →' }).click(); await idle(); await shot('09-step5')
await p.getByRole('button', { name: /^내 경험 \d/ }).click(); await shot('10-drawer'); await p.getByRole('button', { name: '닫기 ✕' }).click()
await p.getByTitle('시연 도구').click(); await shot('11-demo'); await p.getByTitle('시연 도구').click()
await p.reload(); await p.waitForTimeout(800); await shot('12-reload')
await p.getByRole('button', { name: '공고 분석' }).first().click()
await p.getByRole('button', { name: '예시 공고 넣기' }).click()
await p.getByRole('button', { name: '공고 나눠 읽기' }).click(); await p.waitForTimeout(1500); await shot('13-analyze')
await p.getByRole('button', { name: '재취업 이야기' }).first().click(); await shot('14-story')
await close()
